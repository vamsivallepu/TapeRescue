#!/usr/bin/env python3
"""Rebuild VERIFICATION_LOG.md from per-task entries and the pending-item list.

Entries live in verification/entries/<task-id>.md, where <task-id> is a dotted
task number from tasks.md (for example 1.md, 2.1.md, 10.md). Entries are
concatenated in numeric task order (2.1 before 2.10 before 10), followed by
verification/pending.md and then, if present, verification/traceability.md.

Usage: python scripts/collect_verification.py [--root PATH]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TASK_ID_RE = re.compile(r"^\d+(?:\.\d+)*$")

LOG_HEADER = (
    "# TapeRescue Verification Log\n"
    "\n"
    "Generated by `python scripts/collect_verification.py` from "
    "`verification/entries/*.md`, `verification/pending.md` and "
    "`verification/traceability.md`. "
    "Do not edit this file by hand.\n"
)


class CollectError(Exception):
    pass


def task_sort_key(path: Path) -> tuple[int, ...]:
    """Numeric sort key for an entry file named <task-id>.md."""
    stem = path.stem
    if path.suffix != ".md" or not TASK_ID_RE.match(stem):
        raise CollectError(
            f"entry file name {path.name!r} is not a task id such as 1.md or 2.1.md"
        )
    return tuple(int(part) for part in stem.split("."))


def _normalise(text: str) -> str:
    return text.replace("\r\n", "\n").strip("\n") + "\n"


def collect(root: Path) -> str:
    """Return the full VERIFICATION_LOG.md text for the repository at root."""
    entries_dir = root / "verification" / "entries"
    pending = root / "verification" / "pending.md"
    if not pending.is_file():
        raise CollectError(f"missing {pending.relative_to(root)}")

    entries = sorted(entries_dir.glob("*.md"), key=task_sort_key) if entries_dir.is_dir() else []
    keys = [task_sort_key(p) for p in entries]
    if len(set(keys)) != len(keys):
        raise CollectError("duplicate task ids among entry files")

    parts = [LOG_HEADER]
    for entry in entries:
        parts.append(_normalise(entry.read_text(encoding="utf-8")))
    parts.append(_normalise(pending.read_text(encoding="utf-8")))
    traceability = root / "verification" / "traceability.md"
    if traceability.is_file():
        parts.append(_normalise(traceability.read_text(encoding="utf-8")))
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="repository root (default: parent of scripts/)",
    )
    args = parser.parse_args(argv)
    root: Path = args.root
    try:
        text = collect(root)
    except CollectError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    out = root / "VERIFICATION_LOG.md"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
